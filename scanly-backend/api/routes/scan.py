router = APIRouter(
    prefix="/scan",
    tags=["Scanning"],
)

limiter = Limiter(
    key_func=get_remote_address,
)

logger = get_logger(__name__)


# --------------------------------------------------------
# Helper: Gemini Explanation
# --------------------------------------------------------

async def _get_explanation_safely(
    scan_data: dict,
) -> dict:
    """
    Generate Gemini explanation safely.

    Gemini runs in a worker thread so that the synchronous
    Gemini SDK call does not block the FastAPI event loop.

    A hard timeout ensures Gemini can never delay or break
    the actual Scanly detection result.

    If Gemini fails, errors, or times out, gemini_service's
    own FALLBACK_RESPONSE is returned instead.
    """

    try:

        return await asyncio.wait_for(
            asyncio.to_thread(
                gemini_service.generate_explanation,
                scan_data,
            ),
            timeout=gemini_settings.GEMINI_TIMEOUT_SECONDS,
        )

    except asyncio.TimeoutError:

        logger.warning(
            "Gemini explanation timed out"
        )

        return dict(
            gemini_service.FALLBACK_RESPONSE
        )

    except Exception as e:

        logger.warning(
            f"Gemini explanation errored: {e}"
        )

        return dict(
            gemini_service.FALLBACK_RESPONSE
        )


# --------------------------------------------------------
# Helper: Save Scan History
# --------------------------------------------------------

def _save_to_db(
    input_text: str,
    result: dict,
    scan_type: str = "text",
):
    """
    Save completed scan into MongoDB.

    Any database failure is logged but does NOT
    stop the API response.
    """

    try:

        doc = {
            "input_text": input_text,
            "final_score": result.get("final_score", 0),
            "category": result.get("category", "Unknown"),
            "confidence": result.get("confidence", 0.0),
            "ml_score": result.get("ml_score", 0),
            "rule_score": result.get("rule_score", 0),
            "url_score": result.get("url_score", 0),
            "matched_keywords": result.get(
                "matched_keywords",
                [],
            ),
            "flagged_urls": result.get(
                "flagged_urls",
                [],
            ),
            "explanation": result.get(
                "explanation",
                "",
            ),
            "gemini": result.get(
                "gemini",
                {},
            ),
            "model_version": result.get(
                "model_version",
                "roberta-base-finetuned-v1",
            ),
            "scan_type": scan_type,
            "timestamp": datetime.now(
                timezone.utc
            ).isoformat(),
        }

        scans_collection.insert_one(doc)

        logger.info(
            f"Saved {scan_type} scan "
            f"to MongoDB "
            f"(score={result.get('final_score')})"
        )

    except Exception as e:

        logger.warning(
            f"Failed to save scan history: {e}"
        )


# --------------------------------------------------------
# POST /scan/text
# --------------------------------------------------------

@router.post(
    "/text",
    response_model=ScanResponse,
)
@limiter.limit("10/minute")
async def scan_text(
    request: Request,
    body: ScanRequest,
):
    """
    Scan a text message.

    Pipeline:
    RoBERTa
        ↓
    Rule Engine
        ↓
    URL Checker
        ↓
    Final Weighted Score
        ↓
    Gemini Explanation
    """

    logger.info(
        f"Text scan request "
        f"({len(body.text)} characters)"
    )

    text = body.text

    if body.url:
        text += " " + body.url

    try:

        result = run_scan(text)

    except Exception as e:

        logger.error(
            f"Scoring pipeline failed: {e}"
        )

        raise ModelNotLoadedError()

    # ----------------------------------------------------
    # Gemini explanation (explanation-only, never detection)
    # `result["explanation"]` (str) is untouched — Gemini's
    # structured output goes into a separate `gemini` field.
    # ----------------------------------------------------

    scan_data = {
        "scan_type": "text",
        "category": result["category"],
        "score": result["final_score"],
        "reasons": result.get(
            "matched_keywords",
            [],
        ),
        "original_input": body.text,
    }

    gemini_explanation = await _get_explanation_safely(
        scan_data
    )

    result["gemini"] = gemini_explanation

    _save_to_db(
        body.text,
        result,
        scan_type="text",
    )

    return ScanResponse(
        status="success",
        input_text=body.text,
        final_score=result["final_score"],
        category=result["category"],

        # New fields
        confidence=result.get("confidence"),
        model_version=result.get("model_version"),
        processing_time_ms=result.get("processing_time_ms"),

        # Existing fields
        ml_score=result["ml_score"],
        rule_score=result["rule_score"],
        url_score=result["url_score"],
        matched_keywords=result["matched_keywords"],
        explanation=result.get("explanation", ""),

        # Gemini explanation
        gemini=gemini_explanation,
    )


