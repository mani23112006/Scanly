"""
===========================================================
SCANLY — Scan Routes
===========================================================

Purpose
-------
This file contains all scanning-related API endpoints.

Endpoints
---------
POST /scan/text
    • Scan plain text for scam indicators.
    • Pipeline:
      RoBERTa → Rule Engine → URL Checker → Final Score
      → Gemini Explanation

POST /scan/image
    • Scan screenshots/images.
    • Pipeline:
      OCR → RoBERTa → Rule Engine → URL Checker → Final Score
      → Gemini Explanation

POST /scan/url
    • Analyse a single URL.
    • Uses rule-based URL analysis only (no ML model).
    • → Gemini Explanation

Important
---------
Scanly's existing ML/rule-based pipeline remains the
source of truth for scam detection.

Gemini NEVER performs scam detection.
Gemini only explains the result already generated by Scanly.
If Gemini fails or times out, a fallback explanation is used —
the scan result itself is never blocked or changed by Gemini.

NOTE on response models (see models.py):
- `explanation` is a plain str — the existing rule/ML-generated
  explanation your scorer already produces. This is left as-is.
- `gemini` is a separate Optional[GeminiExplanation] field — this
  is where Gemini's structured output goes. The two are NOT the
  same field; do not overwrite `explanation` with Gemini's dict.
"""

import asyncio
