# POST /scan/image
# --------------------------------------------------------

@router.post(
    "/image",
    response_model=ImageScanResponse,
)
@limiter.limit("5/minute")
async def scan_image(
    request: Request,
    file: UploadFile = File(...),
):
    """
    Scan an uploaded screenshot.

    Pipeline:
    OCR
        ↓
    RoBERTa
        ↓
    Rule Engine
        ↓
    URL Checker
        ↓
    Final Score
        ↓
    Gemini Explanation
    """

    logger.info(
        f"Image scan request: "
        f"{file.filename} "
        f"({file.content_type})"
    )

    result = await _image_service(file)

    # ----------------------------------------------------
    # Gemini explanation (explanation-only, never detection)
    # `result["explanation"]` (str, from the scorer) is left
    # untouched — Gemini's output goes into `result["gemini"]`.
    # ----------------------------------------------------

    ocr_text = result.get("extracted_text", "")

    scan_data = {
        "scan_type": "image",
        "category": result.get("category", "Unknown"),
        "score": result.get("final_score", 0),
        "reasons": result.get(
            "matched_keywords",
            [],
        ),
        "original_input": ocr_text,
        "ocr_text": ocr_text,
    }

    gemini_explanation = await _get_explanation_safely(
        scan_data
    )

    result["gemini"] = gemini_explanation

    _save_to_db(
        ocr_text,
        result,
        scan_type="image",
    )

    return result


