    result = scan_url_only(body.url)

    # ----------------------------------------------------
    # Gemini explanation (explanation-only, never detection)
    # `result["explanation"]` (str) is untouched — Gemini's
    # structured output goes into a separate `gemini` field.
    # ----------------------------------------------------

    scan_data = {
        "scan_type": "url",
        "category": result.get("category", "Unknown"),
        "score": result.get("final_score", 0),
        "reasons": result.get("reasons", []),
        "original_input": body.url,
    }

    gemini_explanation = await _get_explanation_safely(
        scan_data
    )

    result["gemini"] = gemini_explanation

    _save_to_db(
        body.url,
        result,
        scan_type="url",
    )

    return URLScanResponse(**result)